package com.molo.payment_api.user;

import jakarta.persistence.*;
import java.time.LocalDateTime;

/**
 * Quelques notions importantes :
 * - `@Enumerated(EnumType.STRING)` stocke `USER` ou `ADMIN` dans la base.
 * - `unique = true` empêche deux utilisateurs d'avoir la même adresse email.
 * - Le mot de passe sera stocké sous forme de hash BCrypt, jamais en clair.
 */

@Entity
@Table(name = "app_users")
public class User {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false, unique = true)
    private String email;

    @Column(nullable = false)
    private String password;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private UserRole role;

    private LocalDateTime createdAt;

    @PrePersist
    void prePersist() {
        if (createdAt == null) {
            createdAt = LocalDateTime.now();
        }
    }

    public Long getId() {
        return id;
    }

    public String getEmail() {
        return email;
    }

    public String getPassword() {
        return password;
    }

    public UserRole getRole() {
        return role;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public void setPassword(String password) {
        this.password = password;
    }

    public void setRole(UserRole role) {
        this.role = role;
    }
}
